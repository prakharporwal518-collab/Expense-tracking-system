/**
 * SQLite and Postgres differ in small, mechanical ways. Rather than maintain two
 * copies of every query, queries are written once in SQLite-flavoured SQL with
 * `?` placeholders and translated here.
 *
 * Only the differences this app actually relies on are handled; anything else
 * must be written portably at the call site.
 */

/** Placeholders: SQLite uses `?`, Postgres uses `$1, $2, ...`. */
export function toPgPlaceholders(sql) {
  let index = 0;
  let out = '';
  let quote = null;

  for (let i = 0; i < sql.length; i++) {
    const ch = sql[i];
    // Never rewrite a `?` that sits inside a string literal.
    if (quote) {
      out += ch;
      if (ch === quote) quote = null;
      continue;
    }
    if (ch === "'" || ch === '"') {
      quote = ch;
      out += ch;
      continue;
    }
    out += ch === '?' ? `$${++index}` : ch;
  }
  return out;
}

/** Statement-level rewrites for constructs Postgres spells differently. */
export function toPostgres(sql) {
  let out = sql;
  // ISO-8601 text timestamps, matching what JS Date#toISOString produces.
  out = out.replace(/datetime\('now'\)/gi, `to_char(now() at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')`);
  out = out.replace(/strftime\('%Y-%m-%dT%H:%M:%fZ'\s*,\s*'now'\)/gi, `to_char(now() at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')`);
  // date(col) over an ISO string is just its first 10 characters in both engines.
  out = out.replace(/\bdate\(([a-z_.]+)\)/gi, 'substr($1,1,10)');
  return toPgPlaceholders(out);
}

/**
 * Postgres needs INSERT ... RETURNING id to report a generated key, which is
 * what SQLite hands back as lastInsertRowid. Every table in this schema has an
 * `id`, so this is safe to add automatically.
 */
export function withReturningId(sql) {
  const trimmed = sql.trim();
  if (!/^insert\s/i.test(trimmed)) return { sql, returnsId: false };
  if (/\breturning\b/i.test(trimmed)) return { sql, returnsId: true };
  return { sql: `${trimmed.replace(/;\s*$/, '')} RETURNING id`, returnsId: true };
}

/** Substitutions that let one schema definition serve both engines. */
export const SCHEMA_TOKENS = {
  sqlite: {
    PK: 'INTEGER PRIMARY KEY AUTOINCREMENT',
    NOW: "strftime('%Y-%m-%dT%H:%M:%fZ','now')",
    TEXT: 'TEXT',
    INT: 'INTEGER',
    REAL: 'REAL'
  },
  postgres: {
    PK: 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
    NOW: `to_char(now() at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')`,
    TEXT: 'TEXT',
    INT: 'BIGINT',
    REAL: 'DOUBLE PRECISION'
  }
};

export function renderSchema(sql, dialect) {
  const tokens = SCHEMA_TOKENS[dialect];
  if (!tokens) throw new Error(`Unknown dialect "${dialect}"`);
  return sql.replace(/\{\{(\w+)\}\}/g, (match, key) => {
    if (!(key in tokens)) throw new Error(`Unknown schema token ${match}`);
    return tokens[key];
  });
}
